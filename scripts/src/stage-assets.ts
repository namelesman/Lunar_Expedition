/**
 * Stage the static assets project "lunar-expedition-assets" (served at
 * https://lunar-expedition-assets.vercel.app, NEXT_PUBLIC_ASSETS_BASE_URL of
 * the app) in data/cache/assets-site/:
 *
 *   public/models, public/sky   copied from apps/web/public (uploaded, ~15 MB)
 *   build/dem-tiles.mjs         scripts/src/dem-tiles.ts bundled with esbuild
 *   vercel.json                 the Vercel build downloads the NASA rasters
 *                               (SHA-256 checked) and writes public/dem/,
 *                               plus CORS and cache headers
 *
 * The DEM tiles (~0.6 GB) are generated by the build, not uploaded: a Vercel
 * Hobby CLI deployment may upload at most 100 MB of source files, while files
 * created during a build have no such limit (vercel.com/docs/limits).
 * The project link (.vercel/) is kept.
 *
 * Usage:
 *   npm run assets:stage
 *   cd data/cache/assets-site && vercel deploy --prod
 */
import { cp, mkdir, rm, writeFile } from "node:fs/promises";
import { existsSync } from "node:fs";
import { join } from "node:path";
import { build } from "esbuild";
import { ROOT } from "./lib/paths";

const SITE = join(ROOT, "data/cache/assets-site");
const OUT = join(SITE, "public");
const PUBLIC = join(ROOT, "apps/web/public");
const FOLDERS = ["models", "sky"];

for (const f of ["public", "build", "vercel.json", "index.html", "models", "sky"])
  await rm(join(SITE, f), { recursive: true, force: true });
await mkdir(OUT, { recursive: true });
for (const f of FOLDERS) {
  const src = join(PUBLIC, f);
  if (!existsSync(src))
    throw new Error(`${src} missing — run glb:optimize / sky:textures first`);
  await cp(src, join(OUT, f), { recursive: true });
}

await build({
  entryPoints: [join(ROOT, "scripts/src/dem-tiles.ts")],
  outfile: join(SITE, "build/dem-tiles.mjs"),
  bundle: true,
  platform: "node",
  format: "esm",
  target: "node22",
  // CommonJS dependencies call require() for Node built-ins.
  banner: {
    js: 'import { createRequire } from "node:module"; const require = createRequire(import.meta.url);',
  },
  logLevel: "warning",
});

const cors = { key: "Access-Control-Allow-Origin", value: "*" };
const week = {
  key: "Cache-Control",
  value: "public, max-age=604800, stale-while-revalidate=86400",
};
await writeFile(
  join(SITE, "vercel.json"),
  JSON.stringify(
    {
      $schema: "https://openapi.vercel.sh/vercel.json",
      framework: null,
      buildCommand:
        "node --max-old-space-size=6144 build/dem-tiles.mjs --download --raw .nasa-raw --out public/dem --check 2000",
      outputDirectory: "public",
      headers: [
        {
          source: "/models/(.*)",
          headers: [
            cors,
            week,
            { key: "Content-Type", value: "model/gltf-binary" },
          ],
        },
        { source: "/sky/(.*)", headers: [cors, week] },
        {
          // Versioned tile paths (dem/v1/…): a new layout gets a new folder.
          source: "/dem/v1/(.*)",
          headers: [
            cors,
            {
              key: "Cache-Control",
              value: "public, max-age=2592000, stale-while-revalidate=86400",
            },
            { key: "Content-Type", value: "application/octet-stream" },
          ],
        },
        {
          source: "/dem/manifest.json",
          headers: [
            cors,
            { key: "Cache-Control", value: "public, max-age=600" },
          ],
        },
      ],
    },
    null,
    2,
  ),
);
await writeFile(
  join(OUT, "index.html"),
  `<!doctype html><meta charset="utf-8"><title>Lunar Expedition assets</title>
<p>Web-optimized derivatives of NASA data for the Lunar Landing Site Navigator (NASA Space Apps Challenge 2026):
the SVS LRO Moon model (svs.gsfc.nasa.gov/14959; LROC + LOLA, NASA/GSFC/ASU), the SVS Deep Star Maps 2020
(svs.gsfc.nasa.gov/4851) and LOLA elevation tiles (dem/) cut from the CGI Moon Kit (svs.gsfc.nasa.gov/4720)
and the LOLA GDR polar DEMs (imbrium.mit.edu, PDS Geosciences Node).</p>
`,
);
console.log(`staged ${FOLDERS.join(", ")} + DEM tile build in ${SITE}`);
