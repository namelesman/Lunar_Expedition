async function sha256(path: string): Promise<string> {
  const h = createHash("sha256");
  await pipeline(createReadStream(path), h);
  return h.digest("hex");
}

/** Path of a raw input; downloads it (with --download) when missing. */
async function ensureRaw(f: RawFile): Promise<string> {
  const dst = join(RAW, f.rel);
  if (existsSync(dst)) return dst;
  if (!flag("download")) return dst;
  await mkdir(dirname(dst), { recursive: true });
  for (const url of f.urls) {
    const tmp = `${dst}.part`;
    const t0 = Date.now();
    try {
      const res = await fetch(url);
      if (!res.ok || !res.body) throw new Error(`HTTP ${res.status}`);
      await pipeline(
        Readable.fromWeb(res.body as import("node:stream/web").ReadableStream),
        createWriteStream(tmp),
      );
      const got = await sha256(tmp);
      if (got !== f.sha256) throw new Error(`SHA-256 ${got} ≠ ${f.sha256}`);
      await rename(tmp, dst);
      const mb = (await stat(dst)).size / 1e6;
      console.log(
        `downloaded ${url} (${mb.toFixed(0)} MB, ${(mb / ((Date.now() - t0) / 1000)).toFixed(1)} MB/s)`,
      );
      return dst;
    } catch (e) {
      console.warn(`download failed ${url}: ${(e as Error).message}`);
      await rm(tmp, { force: true });
    }
  }
  throw new Error(`could not download ${f.rel}`);
}

// ------------------------------------------------------------------ layers
interface Layer {
  spec: DemLayerSpec;
  /** Row-major pixels of the whole raster. */
  data: Uint16Array | Int16Array;
  /** Full-raster sampler (reference for the self-check). */
  full: DemSampler;
}

/** Block mean (k×k) of a polar raster: a coarser grid on the same projection. */
function averagePolar(src: PolarDem, k: number): {
  grid: PolarGrid;
  data: Int16Array;
} {
  const n = src.size,
    m = Math.floor(n / k);
  const out = new Int16Array(m * m);
  for (let y = 0; y < m; y++) {
    for (let x = 0; x < m; x++) {
      let s = 0;
      for (let j = 0; j < k; j++) {
        const row = (y * k + j) * n + x * k;
        for (let i = 0; i < k; i++) s += src.data[row + i];
      }
      out[y * m + x] = Math.round(s / (k * k));
    }
  }
  // Coarse pixel p covers fine pixels k·p … k·p + k − 1: centre at k·p + (k−1)/2.
  return {
    grid: {
      pole: "south",
      size: m,
      center: (src.center - (k - 1) / 2) / k,
      scaleM: src.scaleM * k,
      edgeLat: src.grid.edgeLat,
      scale: src.grid.scale,
    },
    data: out,
  };
}

/**
 * Polar cap of a global equirectangular DEM resampled (bilinear, the same
 * sampler the horizon uses) onto a polar stereographic grid. Near the poles an
 * equirectangular tile holds a sliver of terrain stretched over 320 columns,
 * and a 300 km radius spans every longitude: a cap costs ~1 MB per site where
 * equirectangular tiles cost up to ~15 MB.
 */
function polarCap(
  src: GlobalDem,
  id: string,
  pole: "south" | "north",
  edgeLat: number,
  scaleM: number,
): Layer {
  const radiusPx = Math.ceil(polarRho({ pole }, edgeLat) / scaleM) + 2;
  const size = 2 * radiusPx + 1;
  const grid: PolarGrid = { pole, size, center: radiusPx, scaleM, edgeLat, scale: 0.5 };
  const data = new Int16Array(size * size);
  for (let row = 0; row < size; row++) {
    for (let col = 0; col < size; col++) {
      const p = polarPixelToLatLon(grid, col, row);
      data[row * size + col] = Math.round(src.sample(p.lat, p.lon) / grid.scale);
    }
  }
  const name = `${src.name} resampled to ${scaleM.toFixed(0)} m/px ${pole} polar stereographic (|lat| ≥ ${Math.abs(edgeLat)}°)`;
  const spec: DemLayerSpec = { kind: "polar-stereo", id, name, dtype: "int16", tilePx: 128, ...grid };
  return { spec, data, full: layerDem(spec, { pixel: (x, y) => data[y * size + x] }) };
}

/** Arc length of one pixel of a global DEM in latitude (m). */
const pixelArcM = (ppd: number) => (MOON_RADIUS_M * Math.PI) / 180 / ppd;

async function loadLayers(): Promise<{ near: Layer[]; far: Layer[] }> {
  const g64 = await GlobalDem.load(await ensureRaw(RAW_FILES.ldem64));
  const g16 = await GlobalDem.load(await ensureRaw(RAW_FILES.ldem16));
  const global = (dem: GlobalDem, id: string, tilePx: number): Layer => ({
    spec: { kind: "equirect", id, name: dem.name, dtype: "uint16", tilePx, ...dem.grid },
    data: dem.data,
    full: dem,
  });
  // Near band: the equirectangular ldem_64 itself wherever the budget allows.
  // Resampling it changes the bilinear surface within the first few hundred
  // meters, where the horizon is most sensitive (up to 1.9° at IM-1 for a
  // 237 m cap), so a cap is used only north of 85°N (no LOLA north product
  // in the pipeline; row 85–90°N alone is 10 MB of tiles), at 1/4 of the
  // ldem_64 spacing. The south pole has LDEM_80S_80M.
  const near: Layer[] = [
    polarCap(g64, "ldem-64-n", "north", 85, pixelArcM(64) / 4),
    global(g64, "ldem-64", 320),
  ];
  // Far band (50–300 km): caps at half the ldem_16 spacing; same horizon as
  // the equirectangular raster (max 0.185° vs ldem_64 for the curated sites).
  const far: Layer[] = [
    polarCap(g16, "ldem-16-s", "south", -60, pixelArcM(16) / 2),
    polarCap(g16, "ldem-16-n", "north", 60, pixelArcM(16) / 2),
    global(g16, "ldem-16", 480),
  ];

  for (const f of [RAW_FILES.p80img, RAW_FILES.p80lbl, RAW_FILES.p75img, RAW_FILES.p75lbl])
    await ensureRaw(f);
  const p80 = await PolarDem.load(join(RAW, "lola-polar/LDEM_80S_80M"));
  const p75 = await PolarDem.load(join(RAW, "lola-polar/LDEM_75S_120M"));
  if (p80) {
    near.unshift({
      spec: { kind: "polar-stereo", id: "polar-s-80m", name: p80.name, dtype: "int16", tilePx: 128, ...p80.grid },
      data: p80.data,
      full: p80,
    });
  } else console.warn("LDEM_80S_80M not found: no polar near layer");
  if (p75) {
    const k = 8;
    const { grid, data } = averagePolar(p75, k);
    const name = `LOLA ${p75.file} averaged ${k}×${k} (${grid.scaleM} m/px polar stereographic, imbrium.mit.edu LOLA GDR)`;
    const spec: DemLayerSpec = { kind: "polar-stereo", id: "polar-s-960m", name, dtype: "int16", tilePx: 128, ...grid };
    far.unshift({ spec, data, full: layerDem(spec, { pixel: (x, y) => data[y * grid.size + x] }) });
  } else console.warn("LDEM_75S_120M not found: no polar far layer");
  return { near, far };
}

// ------------------------------------------------------------------- tiles
function tileBytes(l: Layer, index: number): Buffer {
  const t = tileRect(l.spec, index);
  const W = layerWidth(l.spec);
  const Ctor = l.spec.dtype === "uint16" ? Uint16Array : Int16Array;
  const px = new Ctor(t.w * t.h);
  for (let y = 0; y < t.h; y++) {
    const s = (t.y0 + y) * W + t.x0;
    px.set(l.data.subarray(s, s + t.w), y * t.w);
  }
  return Buffer.from(px.buffer, px.byteOffset, px.byteLength);
}

async function writeTiles(
  manifest: DemManifest,
  l: Layer,
): Promise<{ count: number; bytes: number }> {
  const n = tileCols(l.spec) * tileRows(l.spec);
  let count = 0,
    bytes = 0;
  await mkdir(join(OUT, TILES_DIR, l.spec.id), { recursive: true });
  for (let i = 0; i < n; i++) {
    if (!tileExists(l.spec, i)) continue;
    const gz = gzipSync(tileBytes(l, i), { level: LEVEL });
    await writeFile(join(OUT, tilePath(manifest, l.spec, i)), gz);
    count++;
    bytes += gz.length;
  }
  return { count, bytes };
}

// -------------------------------------------------------------- self-check
function mulberry32(seed: number) {
  return () => {
    seed |= 0;
    seed = (seed + 0x6d2b79f5) | 0;
    let t = Math.imul(seed ^ (seed >>> 15), 1 | seed);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

function checkPoints(spec: DemLayerSpec, n: number): { lat: number; lon: number }[] {
  const rnd = mulberry32(0x5eed + spec.tilePx);
  const pts: { lat: number; lon: number }[] = [];
  const eps = 1e-7;
  if (spec.kind === "equirect") {
    for (let i = 0; i < n; i++)
      pts.push({ lat: (Math.asin(2 * rnd() - 1) * 180) / Math.PI, lon: rnd() * 360 - 180 });
    const tileDeg = spec.tilePx / spec.ppd;
    // Tile edges (both sides, including the ±180° seam) and the poles.
    for (let lon = -180; lon <= 180; lon += tileDeg)
      for (const d of [-eps, 0, eps, 0.5 / spec.ppd, -0.5 / spec.ppd])
        pts.push({ lat: rnd() * 180 - 90, lon: lon + d });
    for (let lat = -90; lat <= 90; lat += tileDeg)
      for (const d of [-eps, 0, eps, 0.5 / spec.ppd, -0.5 / spec.ppd])
        pts.push({ lat: Math.max(-90, Math.min(90, lat + d)), lon: rnd() * 360 - 180 });
    for (const lat of [90, -90, 89.999, -89.999]) pts.push({ lat, lon: rnd() * 360 - 180 });
  } else {
    const size = spec.size;
    for (let i = 0; i < n; i++)
      pts.push(polarPixelToLatLon(spec, rnd() * size, rnd() * size));
    // Tile edges in pixel space and the coverage edge.
    for (let k = spec.tilePx; k < size; k += spec.tilePx)
      for (const d of [-1, -0.5, 0, 0.5])
        for (let j = 0; j < 8; j++) {
          pts.push(polarPixelToLatLon(spec, k + d, rnd() * size));
          pts.push(polarPixelToLatLon(spec, rnd() * size, k + d));
        }
    for (let i = 0; i < 400; i++) pts.push({ lat: spec.edgeLat + (rnd() - 0.5) * 0.02, lon: rnd() * 360 - 180 });
    const pole = spec.pole === "south" ? -90 : 90;
    pts.push({ lat: pole, lon: 0 }, { lat: pole * 0.999999, lon: 123 });
  }
  return pts;
}

async function selfCheck(manifest: DemManifest, l: Layer): Promise<void> {
  const store = new TileStore(l.spec);
  const tiled = layerDem(l.spec, store);
  const load = async (x: number, y: number) => {
    const i = tileIndexOf(l.spec, x, y);
    if (store.has(i)) return;
    const gz = await readFile(join(OUT, tilePath(manifest, l.spec, i)));
    store.set(i, decodeTile(l.spec, i, gunzipSync(gz)));
  };
  const pts = checkPoints(l.spec, CHECK_POINTS);
  let mismatches = 0,
    covered = 0;
  for (const p of pts) {
    const need: [number, number][] = [];
    if (tiled.footprint(p.lat, p.lon, (x, y) => need.push([x, y]))) covered++;
    for (const [x, y] of need) await load(x, y);
    const a = l.full.sample(p.lat, p.lon),
      b = tiled.sample(p.lat, p.lon);
    if (!Object.is(a, b)) {
      if (mismatches++ < 5)
        console.error(`  mismatch ${l.spec.id} at ${p.lat},${p.lon}: full ${a} tiled ${b}`);
    }
  }
  if (mismatches || store.missing)
    throw new Error(`self-check ${l.spec.id}: ${mismatches} mismatches, ${store.missing} missing pixels`);
  console.log(`  self-check ${l.spec.id}: ${pts.length} points (${covered} covered) bit-identical`);
}

// --------------------------------------------------------------- budget
async function siteBytes(manifest: DemManifest, lat: number, lon: number) {
  const need = requiredTiles(manifest, lat, lon);
  let bytes = 0,
    tiles = 0;
  const parts: string[] = [];
  for (const [id, set] of need) {
    let b = 0;
    for (const i of set)
      b += (await stat(join(OUT, tilePath(manifest, manifest.layers[id], i)))).size;
    bytes += b;
    tiles += set.size;
    parts.push(`${id} ${set.size} (${(b / 1e6).toFixed(2)} MB)`);
  }
  return { bytes, tiles, parts };
}

async function budget(manifest: DemManifest): Promise<void> {
  const probes: [string, number, number][] = [
    ["equator (Apollo 11)", 0.67416, 23.47314],
    ["tile corner 5N 5E", 5, 5],
    ["mid-latitude 45S 178E", -45.4561, 177.5885],
    ["IM-1 80.13S", -80.13, 1.44],
    ["Shackleton 89.67S", -89.67, 129.78],
    ["north 85N", 85, 0],
    ["north pole 89.5N", 89.5, 45],
  ];
  console.log("download per site (compressed):");
  for (const [label, lat, lon] of probes) {
    const { bytes, tiles, parts } = await siteBytes(manifest, lat, lon);
    console.log(
      `  ${label.padEnd(24)} ${(bytes / 1e6).toFixed(2).padStart(5)} MB, ${String(tiles).padStart(3)} tiles: ${parts.join(", ")}`,
    );
  }
  // Worst case near the layer edges (tile corners, cap edges).
  let worst = { bytes: 0, lat: 0, lon: 0 };
  for (const lat of [-79.9, -77.5, -75, -72.5, -70, -65, -60.1, -55, 55, 59.9, 65, 70, 75, 80, 82.5, 84.9])
    for (const lon of [0, 15, 29.9]) {
      const { bytes } = await siteBytes(manifest, lat, lon);
      if (bytes > worst.bytes) worst = { bytes, lat, lon };
    }
  console.log(`  worst of 48 edge probes: ${(worst.bytes / 1e6).toFixed(2)} MB at ${worst.lat}, ${worst.lon}`);
}

// ------------------------------------------------------------------- main
async function main(): Promise<void> {
  const t0 = Date.now();
  const { near, far } = await loadLayers();
  const layers = [...near, ...far];
  const manifest: DemManifest = {
    version: 1,
    tilesDir: TILES_DIR,
    near: near.map((l) => l.spec.id),
    far: far.map((l) => l.spec.id),
    layers: Object.fromEntries(layers.map((l) => [l.spec.id, l.spec])),
    bytes: {},
    tileCount: {},
    generatedBy: "scripts/src/dem-tiles.ts",
  };
  await rm(join(OUT, TILES_DIR), { recursive: true, force: true });
  for (const l of layers) {
    const { count, bytes } = await writeTiles(manifest, l);
    manifest.bytes![l.spec.id] = bytes;
    manifest.tileCount![l.spec.id] = count;
    console.log(
      `${l.spec.id.padEnd(13)} ${layerWidth(l.spec)}×${layerHeight(l.spec)} → ${count} tiles, ${(bytes / 1e6).toFixed(1)} MB`,
    );
    await selfCheck(manifest, l);
  }
  await writeFile(join(OUT, "manifest.json"), JSON.stringify(manifest, null, 2));
  await budget(manifest);
  console.log(`wrote ${OUT} in ${((Date.now() - t0) / 1000).toFixed(0)} s`);
}

await main();
