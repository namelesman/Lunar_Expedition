/**
 * LOLA DEM tiles for terrain horizons computed in the browser (custom points).
 *
 * Layers (manifest.json lists them finest first for each distance band):
 *   near (≤ 50 km from the site)
 *     polar-s-80m   LOLA GDR LDEM_80S_80M, 80 m/px south polar stereographic,
 *                   lat ≤ −80°, 128×128 px tiles (int16, h = dn·0.5)
 *     ldem-64-n     ldem_64 resampled to a 118 m north polar stereographic
 *                   grid, lat ≥ 85°N (equirectangular rows there cost 10 MB)
 *     ldem-64       CGI Moon Kit ldem_64_uint.tif, 64 px/deg (≈474 m),
 *                   5°×5° tiles of 320×320 px (uint16, h = dn·0.5 − 10000)
 *   far (50–300 km)
 *     polar-s-960m  LOLA GDR LDEM_75S_120M averaged 8×8 → 960 m/px, lat ≤ −75°
 *     ldem-16-s/-n  ldem_16 resampled to 948 m polar stereographic grids,
 *                   |lat| ≥ 60°: near a pole a 300 km radius spans every
 *                   longitude, where 30° equirectangular tiles cost ~5 MB
 *     ldem-16       CGI Moon Kit ldem_16_uint.tif, 16 px/deg (≈1.9 km),
 *                   30°×30° tiles of 480×480 px
 *
 * Budget: ≤ ~4 MB downloaded per site (printed at the end of a run).
 *
 * Each tile is the gzip of its raw little-endian pixels. The layouts and the
 * sampling code are in @lunar/core (demTiles.ts, terrain.ts).
 *
 * Self-check: after writing, every layer is read back from the tile files and
 * compared with the full raster at random points and on tile edges (longitude
 * wrap, poles, polar coverage edge): the heights must be bit-identical.
 *
 * The tiles are not committed. In production they are generated by the build
 * of the static assets project (scripts/src/stage-assets.ts bundles this file;
 * the build runs it with --download) because Vercel Hobby limits a CLI upload
 * to 100 MB and the tile set is ~0.6 GB.
 *
 * Usage:
 *   npm run data:dem-tiles [-- --raw data/raw --out apps/web/public/dem]
 *   options: --download (fetch missing NASA rasters, SHA-256 checked)
 *            --check <n> (self-check points per layer, default 4000)
 *            --level <1-9> (gzip level, default 9)
 */
